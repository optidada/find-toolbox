using System;
using EPiServer.Find;
using EPiServer.Find.Api.Querying;
using EPiServer.Find.Api.Querying.Queries;
using System.Linq;
using System.Text.RegularExpressions;

namespace EPiServer.Labs.Find.Toolbox
{
    public static class QueryHelpers
    {
        public static readonly Regex SpaceTabsRegex = new Regex(@"\s+", RegexOptions.Compiled);
        // Quoted phrases | numbers with separators (1,5 / 2.0.1) | terms. Terms may start with a dot (.net)
        // and contain - & ´ ' ` . / : # + (c#, c++, s&n, e-mail, asp.net).
        public static readonly Regex TermsAndQuotedTermsRegex = new Regex(@"(""[^""]+"")|(\d[\d\.\,]*\d)|(\.?\w[\w\-&´'`\.\/:#\+]*)", RegexOptions.Compiled);

        private static readonly string[] AndOrNotOperators = { "AND", "OR", "NOT" };
        private static readonly char[] TrailingPunctuation = { '.', ',', ':', '/', '-' };

        /// <summary>True when the user's query uses AND / OR / NOT and the options say to respect them.</summary>
        public static bool RespectsBooleanOperators(string rawQuery, FindToolboxOptions options)
            => options.BooleanOperators == BooleanOperatorHandling.Respect && HasBooleanOperators(rawQuery);

        /// <summary>A toolbox query with <paramref name="query"/> as text and all settings and state of <paramref name="source"/>.</summary>
        public static MinShouldMatchQueryStringQuery CreateToolboxQuery(string? query, QueryStringQuery source)
        {
            var newQuery = new MinShouldMatchQueryStringQuery(query);
            CopySettings(source, newQuery);
            return newQuery;
        }

        public static string[] GetQueryPhrases(string query) => GetQueryPhrases(query, FindToolboxOptions.Current.MaxQueryTerms);

        private static readonly Regex QuotedPhraseRegex = new Regex(@"""[^""]*""", RegexOptions.Compiled);
        private static readonly Regex BooleanOperatorRegex = new Regex(@"(^|\s)(AND|OR|NOT)(\s|$)", RegexOptions.Compiled);

        /// <summary>
        /// True if the query uses boolean operators: a standalone, upper case AND, OR or NOT outside quotes.
        /// Find's For() escapes all other query syntax (-, +, *, ~, :, parentheses...), so hyphens and pluses
        /// inside or in front of words (e-mail, c++, -dogs) are never operators. Queries with operators are left
        /// exactly as Find interprets them (no synonyms, relevance, fuzzy or wildcard clauses), because rewriting
        /// them would drop the operators and the optional clauses could match excluded documents.
        /// </summary>
        public static bool HasBooleanOperators(string query)
        {
            if (string.IsNullOrEmpty(query))
            {
                return false;
            }

            return BooleanOperatorRegex.IsMatch(QuotedPhraseRegex.Replace(query, " "));
        }

        public static string[] GetQueryPhrases(string query, int maxTerms)
        {
            if (string.IsNullOrWhiteSpace(query))
            {
                return new string[0];
            }

            // Replace double space, tabs with single whitespace and trim space on side
            string cleanedQuery = SpaceTabsRegex.Replace(query, " ").Trim();

            return TermsAndQuotedTermsRegex.Matches(cleanedQuery).Cast<Match>()
                .Select(c => c.Value.Trim())
                .Select(t => t.StartsWith("\"") ? SpaceTabsRegex.Replace(t, " ") : t.TrimEnd(TrailingPunctuation))
                .Where(t => t.Length > 0 && !AndOrNotOperators.Contains(t))
                .Take(Math.Max(1, maxTerms))
                .ToArray();
        }

        [Obsolete("The toolbox extensions find the main query internally; kept for compatibility with 2.x.")]
        public static bool GetFirstQueryStringQuery(ISearchContext context, out IQuery? query, out BoolQuery boolQuery)
        {

            // Check for existing bool query with possible queries within and get the first which would be the one generated by For()
            if (TryGetBoolQuery(context.RequestBody.Query, out boolQuery))
            {
                query = boolQuery.Should.FirstOrDefault();
            }
            else
            {
                query = context.RequestBody.Query;
            }

            return query is QueryStringQuery;
        }

        [Obsolete("The toolbox extensions find the main query internally; kept for compatibility with 2.x.")]
        public static bool TryGetBoolQuery(IQuery query, out BoolQuery currentBoolQuery)
        {
            var existing = query as BoolQuery;
            if (existing != null)
            {
                currentBoolQuery = existing;
            }
            else
            {
                currentBoolQuery = new BoolQuery();
                return false;
            }

            return true;

        }

        public static string GetRawQueryString(IQuery query)
        {
            return (query as QueryStringQuery)?.RawQuery?.ToString() ?? string.Empty;
        }

        /// <summary>
        /// Copies all query_string settings (fields, analyzer, operators, ...) from <paramref name="source"/> to <paramref name="target"/>.
        /// </summary>
        public static void CopySettings(QueryStringQuery source, MultiFieldQueryStringQuery target)
        {
            target.RawQuery = source.RawQuery;
            target.AllowLeadingWildcard = source.AllowLeadingWildcard;
            target.AnalyzeWildcard = source.AnalyzeWildcard;
            target.Analyzer = source.Analyzer;
            target.AutoGeneratePhraseQueries = source.AutoGeneratePhraseQueries;
            target.Boost = source.Boost;
            target.DefaultOperator = source.DefaultOperator;
            target.EnablePositionIncrements = source.EnablePositionIncrements;
            target.FuzzyMinSim = source.FuzzyMinSim;
            target.FuzzyPrefixLength = source.FuzzyPrefixLength;
            target.LowercaseExpandedTerms = source.LowercaseExpandedTerms;
            target.PhraseSlop = source.PhraseSlop;
            target.DefaultField = source.DefaultField;

            if (source is MultiFieldQueryStringQuery multiField && multiField.Fields != null)
            {
                target.Fields = multiField.Fields.ToList();
            }

            if (source is MinShouldMatchQueryStringQuery sourceMsm && target is MinShouldMatchQueryStringQuery targetMsm)
            {
                targetMsm.MinimumShouldMatch = sourceMsm.MinimumShouldMatch;
                targetMsm.Lenient = sourceMsm.Lenient;
                targetMsm.Toolbox = sourceMsm.Toolbox.Clone();
            }
        }

        public static bool IsStringQuoted(string text)
        {
            return text != null && text.Length >= 2 && text.StartsWith("\"") && text.EndsWith("\"");
        }

        public static bool IsStringParenthesized(string text)
        {
            return text != null && text.Length >= 2 && text.StartsWith("(") && text.EndsWith(")");
        }

    }

}